#!/usr/bin/env python3
"""Writes the `# keybind:` lines in lib/agent.py's docstring (Vayu's
keybinding search reads them from the installed copy) and the README's key
table, from PROMPT_KEYS.

    scripts/keybinds.py           rewrite them
    scripts/keybinds.py --check   exit 1 if they're out of date (CI)

Reads agent.py's key table without importing GTK: the table and the keys
module are executed on their own.
"""
import ast
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIALOG = ROOT / "lib" / "agent.py"
README = ROOT / "README.md"
START = "# --- keybindings (generated by scripts/keybinds.py: don't edit by hand) ---"
END = "# --- end keybindings ---"
TSTART = "<!-- keys: generated by scripts/keybinds.py -->"
TEND = "<!-- end keys -->"


def load():
    spec = importlib.util.spec_from_file_location("keys", ROOT / "lib" / "keys.py")
    keys = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(keys)
    tree = ast.parse(DIALOG.read_text())
    ns = {"KEYS": keys, "Bind": keys.Bind}
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.FunctionDef)) and (
                (isinstance(node, ast.FunctionDef) and node.name == "keybind_lines")
                or any(getattr(t, "id", "") in ("PROMPT_KEYS",) for t in getattr(node, "targets", []))):
            exec(compile(ast.Module([node], []), str(DIALOG), "exec"), ns)
    return keys, ns


def table(keys, ns):
    rows = ["| Key | Action |", "|---|---|"]
    for b in ns["PROMPT_KEYS"]:
        if not b.hidden and b.desc:
            rows.append(f"| `{keys.spell(b.seq)}` | {b.desc} |")
    return "\n".join(rows)


def splice(text, start, end, body):
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main():
    keys, ns = load()
    d, r = DIALOG.read_text(), README.read_text()
    nd = splice(d, START, END, "\n".join(ns["keybind_lines"]()))
    nr = splice(r, TSTART, TEND, table(keys, ns))
    if "--check" in sys.argv:
        bad = [p for p, a, b in ((DIALOG, d, nd), (README, r, nr)) if a != b]
        for p in bad:
            print(f"{p.relative_to(ROOT)}: the keys are out of date: run scripts/keybinds.py", file=sys.stderr)
        return 1 if bad else 0
    DIALOG.write_text(nd)
    README.write_text(nr)
    print("wrote the keybind lines and the README key table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
